def _get_exif_data(image_path):
    image = Image.open(image_path)
    exif_data = image._getexif()

    return image.info["parameters"]


def get_meta_from_image(img_path: str, char_name_id_map) -> ImageInfo:
    full_path = os.path.abspath(img_path)  # replace for the image url later
    filename = os.path.basename(img_path)
    imgname = filename.split("/")[-1]
    desc = ".".join(imgname.split(".")[:-1]).lower()

    desc = desc.replace("img/", "")
    desc = desc.replace(".json", "")
    desc = desc.replace("_description", "")
    img_parts = desc.split(" + ")

    # replace \d+ with a regex
    img_parts = [re.sub(r"\d+_", "", part) for part in img_parts]
    char_name = img_parts[0]
    location = img_parts[1].replace("_", " ")
    cloths = img_parts[2].replace("_", " ")

    last_parts = img_parts[3].split("_")

    if "rating" not in last_parts:
        last_parts.insert(0, "rating")

    rating = " ".join(last_parts[:2]).replace("rating", "").strip()
    behavior = " ".join(last_parts[2:4]).replace("behavior", "").strip()
    exif = _get_exif_data(img_path)
    prompt = exif.split("\n")[0]

    with open(full_path, "rb") as f:
        hash = hashlib.file_digest(f, "sha256")

    digest = hash.hexdigest()
    if digest is None:
        raise ValueError("Digest is None")
    result = ImageInfo(
        hash=digest,
        path="file://" + full_path,
        character=char_name_id_map[char_name],
        location=location,
        cloths=cloths,
        rating=rating,
        behavior=behavior,
        prompt=prompt,
        name=imgname,
        char_name=char_name,
    )

    result.hash = digest
    logger.debug(f"Image: {img_path} => {result.model_dump()}")
    return result


