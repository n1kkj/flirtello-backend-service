@deprecated("New upload pipeline is not implemented yet")
def _save_image_batch(session: Session, batch: List[ImageInfo]) -> Tuple[int, int]:
    # ids in the batch are autogenerated and thus incorrect for updates!
    batch_map_hash = {i.hash: i for i in batch}
    batch_map_ids = {i.id: i for i in batch}
    hashes_to_check = list(map(lambda i: i.hash, batch))

    stmt = select(ImageInfo).where(col(ImageInfo.hash).in_(hashes_to_check))
    existing_imgs = session.exec(stmt).all()

    ids_for_update = list(map(lambda i: i.id.hex, existing_imgs))
    hashes_for_update = list(map(lambda i: i.hash, existing_imgs))

    hashes_for_insert = list(filter(lambda i: i not in hashes_for_update, batch_map_hash))

    for i in hashes_for_insert:
        session.add(batch_map_hash[i])

    imgs_to_update = []
    for i in existing_imgs:
        tmp_id = i.id
        _magic_copy(batch_map_hash[i.hash], i)
        i.id = tmp_id
        imgs_to_update.append(i)

    for i in ids_for_update:
        session.add_all(imgs_to_update)

    return len(hashes_for_insert), len(ids_for_update)


@deprecated("New upload pipeline is not implemented yet")
def add_images_from_folder(session, folder: str) -> Tuple[int, int]:
    BATCH_SIZE = 10
    i = 0
    everything = []
    current_batch: List[ImageInfo] = []
    counters = (0, 0)
    for image_path in glob(os.path.join(folder, "**")):
        image_info = get_meta_from_image(image_path)
        current_batch.append(image_info)
        if i == BATCH_SIZE - 1:
            inserted, updated = _save_image_batch(session, current_batch)
            counters = (counters[0] + inserted, counters[1] + updated)
            current_batch = []
        i += 1
        everything.append(image_info)
    if len(current_batch) > 0:
        inserted, updated = _save_image_batch(session, current_batch)  # last batch
        counters = (counters[0] + inserted, counters[1] + updated)
    return counters


